// Trading a Solana token after it migrates to its locked PumpSwap pool, from the token page (23 Oct 2026). The page
// uses PumpSwap's official SDK, bundled for the browser (apps/web/vendor/pumpswap.mjs). The on-chain part (quotes and
// built transactions against a real migrated pool) is in solana.test.mjs; this covers the wallet, the bundle and serving.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import * as web3 from '@solana/web3.js';
import './helpers/browser-modules.mjs';
import { startServer } from '../apps/api/server.mjs';
import { SDK_VERSION } from '../scripts/build-pumpswap-vendor.mjs';
import { STATUS_MIGRATED, PUMPSWAP_COMPUTE_UNITS } from '../packages/solana/client.mjs';

globalThis.solanaWeb3 = web3;
const { SolanaWallet } = await import('../apps/web/solana-wallet.mjs');
const bundle = readFileSync(new URL('../apps/web/vendor/pumpswap.mjs', import.meta.url), 'utf8');

test('the bundle is PumpSwap\'s official SDK at the pinned version, uses the page\'s web3.js and passes the CSP', () => {
  assert.ok(bundle.startsWith(`// Generated by scripts/build-pumpswap-vendor.mjs from @pump-fun/pump-swap-sdk@${SDK_VERSION} (MIT, Pump Fun).`));
  assert.match(bundle, /globalThis\.solanaWeb3/, 'web3.js comes from the page, not a second copy');
  for (const banned of ['eval(', 'new Function', 'Function(']) assert.ok(!bundle.includes(banned), `no ${banned} (script-src 'self' forbids it)`);
  assert.ok(bundle.length < 600_000, `${bundle.length} bytes`);
});

test('the server serves the bundle as JavaScript', async t => {
  const app = await startServer({ port: 0, seed: false });
  t.after(() => app.close());
  const response = await fetch(`${app.url}/vendor/pumpswap.mjs`);
  assert.equal(response.status, 200);
  assert.match(response.headers.get('content-type'), /javascript/);
  assert.equal((await response.text()).length, bundle.length);
});

function wallet({ tokens = 5_000_000n * 10n ** 6n, sol = 2_000_000_000n, limit = 101_000_000n } = {}) {
  const log = { sent: [], trades: [] };
  const w = Object.create(SolanaWallet.prototype);
  const me = web3.Keypair.generate().publicKey, pumpPool = web3.Keypair.generate().publicKey;
  Object.assign(w, {
    publicKey: me, net: { name: 'Solana Devnet', deployment: { programId: me.toBase58() } },
    connection: { getAccountInfo: async () => ({ data: Buffer.alloc(72) }) },
    _client: { ata: () => me, tokenAmount: () => tokens, computeBudget: units => ({ budget: units }) },
    pumpStates: async () => new Map([['m', { pumpPool: pumpPool.toBase58() }]]),
    quoteBalance: async () => sol,
    sendInstructions: async (instructions, extra, message) => { log.sent.push({ instructions, message }); return 'SIG'; },
    pumpSwapModule: { pumpSwapTrade: async args => { log.trades.push(args); return { instructions: ['wrap', 'swap', 'unwrap'], out: 1n, limit, fee: 1n }; } },
  });
  return { w, log, pumpPool };
}
const config = { quoteDecimals: 9, wsol: true, symbol: 'SOL' };
const pool = { status: STATUS_MIGRATED, symbol: 'MADARA', mint: web3.Keypair.generate().publicKey };

test('a migrated token buys and sells through its PumpSwap pool in one signed transaction', async () => {
  let { w, log, pumpPool } = wallet();
  const bought = await w.pumpSwapTrade({ pool, config, action: 'buy', body: { amount: '0.1', slippage: '1' } });
  assert.equal(bought.hash, 'SIG'); assert.equal(bought.message, 'Bought MADARA on PumpSwap.');
  assert.equal(log.trades[0].side, 'buy'); assert.equal(log.trades[0].amount, 100_000_000n, '0.1 SOL in lamports');
  assert.equal(log.trades[0].slippageBps, 100); assert.equal(log.trades[0].pool.toBase58(), pumpPool.toBase58(), 'the token\'s own Elpida-locked pool');
  assert.equal(log.sent.length, 1, 'one transaction');
  assert.deepEqual(log.sent[0].instructions, [{ budget: PUMPSWAP_COMPUTE_UNITS }, 'wrap', 'swap', 'unwrap']);
  assert.match(log.sent[0].message, /buy on PumpSwap/);
  const sold = await w.pumpSwapTrade({ pool, config, action: 'sell', body: { amount: '1000', slippage: '0.5' } });
  assert.equal(sold.message, 'Sold MADARA on PumpSwap.');
  assert.equal(log.trades[1].amount, 1_000n * 10n ** 6n, 'tokens have 6 decimals'); assert.equal(log.trades[1].slippageBps, 50);
});

test('PumpSwap trades are refused before the wallet is asked when funds, amount or slippage are wrong', async () => {
  // A buy may charge up to its slippage limit, so that (plus fee headroom) must be held.
  let { w, log } = wallet({ sol: 101_000_000n, limit: 101_000_000n });
  await assert.rejects(w.pumpSwapTrade({ pool, config, action: 'buy', body: { amount: '0.1', slippage: '1' } }), /may charge up to 0\.101 SOL/);
  ({ w, log } = wallet({ tokens: 10n }));
  await assert.rejects(w.pumpSwapTrade({ pool, config, action: 'sell', body: { amount: '1', slippage: '1' } }), /You hold 0\.00001 MADARA/);
  await assert.rejects(w.pumpSwapTrade({ pool, config, action: 'buy', body: { amount: '0', slippage: '1' } }), /greater than zero/);
  await assert.rejects(w.pumpSwapTrade({ pool, config, action: 'buy', body: { amount: '1', slippage: '9' } }), /Slippage/);
  assert.equal(log.sent.length, 0, 'nothing was sent to the wallet');
});
