// Builds apps/web/vendor/pumpswap.mjs: PumpSwap's official SDK for the browser, used to trade a Solana token after it
// migrates to its locked PumpSwap pool. Run after changing SDK_VERSION, then commit the output:
//   node scripts/build-pumpswap-vendor.mjs
// The SDK and its dependencies are installed in a temporary folder (they are not app dependencies). The page's own
// @solana/web3.js (window.solanaWeb3, loaded from /vendor/solana-web3.js) is used instead of a second copy, so keys
// and instructions are the same classes as everywhere else on the page.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const SDK_VERSION = '2.2.0';
const root = fileURLToPath(new URL('../', import.meta.url));
const out = join(root, 'apps/web/vendor/pumpswap.mjs');
// Importing this file (tests read SDK_VERSION) never builds; only running it does.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildVendor();

async function buildVendor() {
const work = mkdtempSync(join(tmpdir(), 'elpida-pumpswap-'));
try {
  writeFileSync(join(work, 'package.json'), JSON.stringify({ name: 'pumpswap-vendor', private: true, type: 'module' }));
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  execFileSync(npm, ['install', '--no-audit', '--no-fund', '--ignore-scripts', `@pump-fun/pump-swap-sdk@${SDK_VERSION}`, 'bn.js', 'buffer', 'esbuild@0.25.11'], { cwd: work, stdio: 'inherit', shell: process.platform === 'win32' });
  copyFileSync(join(root, 'scripts/pumpswap-vendor-entry.mjs'), join(work, 'entry.mjs'));
  writeFileSync(join(work, 'buffer-shim.mjs'), "import { Buffer } from 'buffer';\nexport { Buffer };\n");
  const { build } = await import(join(work, 'node_modules/esbuild/lib/main.js'));
  const pageWeb3 = {
    name: 'page-solana-web3',
    setup(b) {
      b.onResolve({ filter: /^@solana\/web3\.js$/ }, () => ({ path: 'solana-web3', namespace: 'page' }));
      b.onLoad({ filter: /.*/, namespace: 'page' }, () => ({ contents: 'module.exports = globalThis.solanaWeb3;', loader: 'js' }));
    },
  };
  const sdk = JSON.parse(readFileSync(join(work, 'node_modules/@pump-fun/pump-swap-sdk/package.json'), 'utf8'));
  await build({
    entryPoints: [join(work, 'entry.mjs')], bundle: true, format: 'esm', platform: 'browser', target: 'es2020', minify: true,
    outfile: out, plugins: [pageWeb3], inject: [join(work, 'buffer-shim.mjs')], legalComments: 'none',
    define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
    banner: { js: `// Generated by scripts/build-pumpswap-vendor.mjs from ${sdk.name}@${sdk.version} (${sdk.license}, Pump Fun). Do not edit.` },
    logLevel: 'warning',
  });
  const bytes = readFileSync(out);
  console.log(`Wrote apps/web/vendor/pumpswap.mjs: ${bytes.length.toLocaleString()} bytes, sha256 ${createHash('sha256').update(bytes).digest('hex')}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
}
